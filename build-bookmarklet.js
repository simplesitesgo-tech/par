// Turns sync.js into bookmarklet.js, which the Setup screen uses for the draggable button.
// Run with: node build-bookmarklet.js
const fs = require('fs');
const src = fs.readFileSync(__dirname + '/sync.js', 'utf8')
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('//'))
  .join('\n');
new Function(src);
const out = '// Generated by build-bookmarklet.js from sync.js. Do not edit by hand.\n' +
  'window.PAR_BOOKMARKLET_SOURCE = ' + JSON.stringify(src) + ';\n';
fs.writeFileSync(__dirname + '/bookmarklet.js', out);
console.log('bookmarklet.js written, ' + src.length + ' characters');
